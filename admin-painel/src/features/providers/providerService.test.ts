import { afterEach, beforeEach, expect, it, vi } from 'vitest';
const state = vi.hoisted(() => ({ user: { uid: 'a', getIdToken: async () => 'synthetic-token' } }));
vi.mock('@/shared/auth/session', () => ({ auth: { get currentUser() { return state.user; } } }));
import { getProvider, subscribeProvider, subscribeProviders } from './providerService';
import { clearPanelReads } from '@/shared/api/panelHttp';
let listeners: Map<string, () => void>;
let doc: { visibilityState: string; addEventListener: (key: string, fn: () => void) => void; removeEventListener: (key: string) => void };
beforeEach(() => {
  clearPanelReads(); listeners = new Map();
  doc = { visibilityState: 'visible', addEventListener: (key, fn) => { listeners.set(key, fn); }, removeEventListener: key => { listeners.delete(key); } };
  vi.stubGlobal('document', doc);
  vi.stubGlobal('window', { location: { protocol: 'https:', hostname: 'panel.test', origin: 'https://panel.test', port: '' } });
});
afterEach(() => { vi.unstubAllGlobals(); vi.useRealTimers(); clearPanelReads(); });
it('loads a single sanitized provider, coalesces reads and uses a metadata directory', async () => {
  const fetcher = vi.fn().mockImplementation(async (path: string) => path.endsWith('/b') ? new Response(JSON.stringify({error:{message:'Missing'}}), {status:404}) : new Response(JSON.stringify({ data: path.endsWith('/summaries') ? [] : { id: 'a', name: 'A', details: { systemUrl: 'private', apiToken: 'private' }, integrations: { appName: 'private' } } })));
  vi.stubGlobal('fetch', fetcher);
  const values = await Promise.all([getProvider('a'), getProvider('a')]);
  expect(values[0]).toMatchObject({ id: 'a', name: 'A' }); expect(JSON.stringify(values)).not.toContain('private');
  expect(fetcher).toHaveBeenCalledTimes(1); expect(fetcher.mock.calls[0][0]).toContain('/admin/providers/a');
  expect(await getProvider('b')).toBeNull();
  const emit = vi.fn(); const stop = subscribeProviders(emit);
  await vi.waitFor(() => expect(emit).toHaveBeenCalled()); stop();
  expect(fetcher.mock.calls.some(([path]) => path.endsWith('/summaries'))).toBe(true);
});
it('unchanged data never overwrites drafts; hidden tabs pause polling and resume when visible', async () => {
  vi.useFakeTimers();
  const provider = { id: 'a', themeColor: '#abc' };
  const fetcher = vi.fn().mockImplementation(async () => new Response(JSON.stringify({ data: provider })));
  vi.stubGlobal('fetch', fetcher);
  const emit = vi.fn(); const stop = subscribeProvider('a', emit);
  await vi.advanceTimersByTimeAsync(0); expect(emit).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(15_000); expect(emit).toHaveBeenCalledTimes(1);
  const before = fetcher.mock.calls.length;
  doc.visibilityState = 'hidden'; provider.themeColor = '#def';
  await vi.advanceTimersByTimeAsync(60_000); expect(fetcher).toHaveBeenCalledTimes(before);
  doc.visibilityState = 'visible'; listeners.get('visibilitychange')!();
  await vi.advanceTimersByTimeAsync(0); expect(emit).toHaveBeenCalledTimes(2);
  stop(); await vi.advanceTimersByTimeAsync(30_000); expect(emit).toHaveBeenCalledTimes(2);
});
